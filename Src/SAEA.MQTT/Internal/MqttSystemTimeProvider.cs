using System;

namespace SAEA.MQTT.Internal
{
    /// <summary>
    /// 基于系统 UTC 时钟的时间提供器。
    /// </summary>
    internal sealed class MqttSystemTimeProvider : IMqttTimeProvider
    {
        public static readonly MqttSystemTimeProvider Instance = new MqttSystemTimeProvider();

        public DateTimeOffset UtcNow
        {
            get { return DateTimeOffset.UtcNow; }
        }
    }
}