namespace SAEA.Sockets.Pipeline
{
    /// <summary>
    /// 入站消息的分发方式。
    /// </summary>
    public enum ChannelDispatchMode
    {
        /// <summary>
        /// 每帧写入有界队列，由消费循环按并发额度派发；接收线程与业务执行解耦，是默认行为。
        /// </summary>
        Queued = 0,

        /// <summary>
        /// 无在途消息时由接收泵在当前线程直接执行；某帧一旦挂起，后续帧回落到排队分发，
        /// 等在途清零后恢复内联。要求 <see cref="ChannelPipelineOptions.MessageTimeout"/> 为零，
        /// 否则按 <see cref="Queued"/> 处理。
        /// </summary>
        Inline = 1
    }
}