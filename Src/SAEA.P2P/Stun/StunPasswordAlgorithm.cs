namespace SAEA.P2P.Stun
{
    /// <summary>
    /// STUN 密码算法，用于长期凭据的密钥派生；数值是 PASSWORD-ALGORITHM 属性里的算法编号
    /// </summary>
    public enum StunPasswordAlgorithm : ushort
    {
        /// <summary>
        /// MD5，本轮唯一签发与接受的算法
        /// </summary>
        Md5 = 0x0001,

        /// <summary>
        /// SHA-256，本轮能识别但不签发，遇到时明确回不支持
        /// </summary>
        Sha256 = 0x0002
    }
}