namespace SAEA.P2P.Stun
{
    /// <summary>
    /// STUN 事务失败原因；供调用方按原因决定是否换候选或退回中继
    /// </summary>
    public enum StunTransactionFailure
    {
        /// <summary>
        /// 未失败
        /// </summary>
        None = 0,

        /// <summary>
        /// 重传全部发完并等满 Rm 倍 RTO 仍无应答
        /// </summary>
        Timeout = 1,

        /// <summary>
        /// 调用方取消
        /// </summary>
        Cancelled = 2,

        /// <summary>
        /// 发送动作本身抛出异常，传输已不可用
        /// </summary>
        TransportError = 3
    }
}