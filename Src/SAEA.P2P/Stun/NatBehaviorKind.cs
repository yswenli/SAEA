namespace SAEA.P2P.Stun
{
    /// <summary>
    /// NAT 行为标签：映射行为与过滤行为共用同一组取值。
    /// 映射行为对应 EIM / ADM / APDM，过滤行为对应 EIF / ADF / APDF。
    /// 该标签只用于诊断展示，不参与候选优先级与选路决策。
    /// </summary>
    public enum NatBehaviorKind
    {
        /// <summary>
        /// 未探测或探测失败，无法判定
        /// </summary>
        Unknown = 0,

        /// <summary>
        /// 端点无关：映射对外部端口或过滤对任意来源都不变
        /// </summary>
        EndpointIndependent = 1,

        /// <summary>
        /// 地址相关：行为只随目标或来源地址变化
        /// </summary>
        AddressDependent = 2,

        /// <summary>
        /// 地址端口相关：行为随目标或来源的地址与端口一起变化
        /// </summary>
        AddressAndPortDependent = 3
    }
}