namespace SAEA.P2P.Stun
{
    /// <summary>
    /// STUN 消息类别；数值是消息类型编码里的 2 位类别字段原值，不可随意调整
    /// </summary>
    public enum StunClass
    {
        /// <summary>
        /// 请求，需要事务层重传与应答
        /// </summary>
        Request = 0,

        /// <summary>
        /// 指示，无事务无应答，不得回错误
        /// </summary>
        Indication = 1,

        /// <summary>
        /// 成功应答
        /// </summary>
        SuccessResponse = 2,

        /// <summary>
        /// 错误应答
        /// </summary>
        ErrorResponse = 3
    }
}