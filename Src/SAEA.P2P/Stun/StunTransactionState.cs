namespace SAEA.P2P.Stun
{
    /// <summary>
    /// STUN 事务状态；进入 Completed 或 Failed 后不再接受任何重传与响应
    /// </summary>
    public enum StunTransactionState
    {
        /// <summary>
        /// 等待响应，可能仍在重传
        /// </summary>
        Waiting = 0,

        /// <summary>
        /// 已收到成功或错误应答
        /// </summary>
        Completed = 1,

        /// <summary>
        /// 已超时、被取消或发送失败
        /// </summary>
        Failed = 2
    }
}