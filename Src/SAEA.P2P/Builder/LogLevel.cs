namespace SAEA.P2P.Builder
{
    /// <summary>
    /// 日志等级枚举，数值与 LoggingOptions.Level 的阈值比较方向一致：数值越小越详细
    /// </summary>
    public enum LogLevel
    {
        /// <summary>
        /// 跟踪级，输出全部细节
        /// </summary>
        Trace = 0,
        /// <summary>
        /// 调试级，输出诊断信息
        /// </summary>
        Debug = 1,
        /// <summary>
        /// 信息级，输出常规运行信息
        /// </summary>
        Info = 2,
        /// <summary>
        /// 警告级，输出可恢复的异常情况
        /// </summary>
        Warning = 3,
        /// <summary>
        /// 错误级，输出失败与异常信息
        /// </summary>
        Error = 4
    }
}