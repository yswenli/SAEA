namespace SAEA.P2P.NAT
{
    /// <summary>
    /// 打洞策略，决定直连与中继的优先关系以及是否允许降级
    /// </summary>
    public enum HolePunchStrategy
    {
        /// <summary>
        /// 优先直连打洞，直连失败后再改用中继
        /// </summary>
        PreferDirect = 0,
        /// <summary>
        /// 优先使用中继转发，中继不可用时才尝试直连
        /// </summary>
        PreferRelay = 1,
        /// <summary>
        /// 只允许直连，NAT 不兼容时直接判定失败
        /// </summary>
        DirectOnly = 2,
        /// <summary>
        /// 只走中继，不尝试打洞
        /// </summary>
        RelayOnly = 3
    }
}