namespace SAEA.P2P.NAT
{
    /// <summary>
    /// NAT 类型，按映射与入包过滤的宽松程度从易到难排列
    /// </summary>
    public enum NATType
    {
        /// <summary>
        /// 尚未探测或探测失败，是否可打洞未知
        /// </summary>
        Unknown = 0,
        /// <summary>
        /// 全锥型：内部地址映射固定，任意外部主机都可主动送入
        /// </summary>
        FullCone = 1,
        /// <summary>
        /// 受限锥型：映射固定，仅接受本机曾主动访问过的 IP 发来的包
        /// </summary>
        RestrictedCone = 2,
        /// <summary>
        /// 端口受限锥型：映射固定，仅接受本机曾主动访问过的 IP 与端口发来的包
        /// </summary>
        PortRestrictedCone = 3,
        /// <summary>
        /// 对称型：每个目标地址分配独立映射，最难打洞
        /// </summary>
        Symmetric = 4
    }
}