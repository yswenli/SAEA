namespace SAEA.P2P.Turn
{
    /// <summary>
    /// TURN 控制连接（TCP/TLS）上一条帧的类型，按首字节区分 STUN 报文与 ChannelData 报文。
    /// </summary>
    public enum TurnStreamFrameKind
    {
        /// <summary>
        /// STUN/TURN 报文，首字节落在 0x00 到 0x3F
        /// </summary>
        Stun = 0,

        /// <summary>
        /// ChannelData 报文，首字节落在 0x40 到 0x4F
        /// </summary>
        ChannelData = 1
    }
}