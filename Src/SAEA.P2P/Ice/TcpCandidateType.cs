namespace SAEA.P2P.Ice
{
    /// <summary>
    /// TCP 候选的方向类型；UDP 候选固定为 None
    /// </summary>
    public enum TcpCandidateType
    {
        /// <summary>
        /// 非 TCP 候选，不参与 TCP 方向偏好计算
        /// </summary>
        None = 0,

        /// <summary>
        /// 主动连接对端的被动候选
        /// </summary>
        Active = 1,

        /// <summary>
        /// 被动监听，等待对端连接
        /// </summary>
        Passive = 2,

        /// <summary>
        /// 同时打开，两端同时发起连接
        /// </summary>
        SimultaneousOpen = 3
    }
}