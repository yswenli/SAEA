namespace SAEA.P2P.Ice
{
    /// <summary>
    /// 候选类型，数值即类型优先级
    /// </summary>
    public enum CandidateType
    {
        /// <summary>
        /// 主机候选，来自本地接口
        /// </summary>
        Host = 126,

        /// <summary>
        /// 对端反射候选，由连通性检查动态发现
        /// </summary>
        PeerReflexive = 110,

        /// <summary>
        /// 服务端反射候选，经 STUN 服务器观察到映射地址
        /// </summary>
        ServerReflexive = 100,

        /// <summary>
        /// 中继候选，经 TURN 服务器转发
        /// </summary>
        Relay = 0
    }
}
