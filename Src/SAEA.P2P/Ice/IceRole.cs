namespace SAEA.P2P.Ice
{
    /// <summary>
    /// ICE 角色，发起 ConnectRequest 的一方为控制方
    /// </summary>
    public enum IceRole
    {
        /// <summary>
        /// 控制方：发起 ConnectRequest，负责提名候选对
        /// </summary>
        Controlling = 0,

        /// <summary>
        /// 受控方：响应检查请求，不主动提名
        /// </summary>
        Controlled = 1
    }
}