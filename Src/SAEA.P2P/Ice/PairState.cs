namespace SAEA.P2P.Ice
{
    /// <summary>
    /// 候选对状态，取值与检查表推进顺序一致
    /// </summary>
    public enum PairState
    {
        /// <summary>
        /// 冻结：同 foundation 组内排队，未轮到检查
        /// </summary>
        Frozen = 0,

        /// <summary>
        /// 等待：已解冻，可被选择器挑出做连通性检查
        /// </summary>
        Waiting = 1,

        /// <summary>
        /// 检查中：已发出检查请求，等待响应
        /// </summary>
        InProgress = 2,

        /// <summary>
        /// 已成功：检查通过，可参与提名
        /// </summary>
        Succeeded = 3,

        /// <summary>
        /// 已失败：终态，不再参与检查
        /// </summary>
        Failed = 4
    }
}