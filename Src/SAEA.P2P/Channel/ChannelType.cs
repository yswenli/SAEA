{
    /// <summary>
    /// 节点间通信通道类型
    /// </summary>
    public enum ChannelType
    {
        /// <summary>
        /// 打洞成功后的端到端直连
        /// </summary>
        Direct = 0,
        /// <summary>
        /// 经信令服务器或中继节点转发
        /// </summary>
        Relay = 1,
        /// <summary>
        /// 局域网内通过本地发现建立的直连
        /// </summary>
        Local = 2
    }
}