namespace SAEA.FTP.Model
{
    /// <summary>
    /// 服务端原样输出的控制回复文本，用于 FEAT 这类已经自带换行的多行响应。
    /// 内容按原样写出，不再追加 CRLF。
    /// </summary>
    public sealed class FtpRawText
    {
        /// <summary>
        /// 以完整回复文本创建消息
        /// </summary>
        /// <param name="text">已包含换行符的完整回复文本</param>
        public FtpRawText(string text)
        {
            Text = text ?? string.Empty;
        }

        /// <summary>
        /// 已包含换行符的完整回复文本
        /// </summary>
        public string Text { get; private set; }
    }
}