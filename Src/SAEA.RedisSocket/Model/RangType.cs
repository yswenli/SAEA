namespace SAEA.RedisSocket.Model
{
    /// <summary>
    /// 范围查询端点的开闭方式，编码时通过给端点加 ( 前缀表示不包含
    /// </summary>
    public enum RangType
    {
        /// <summary>
        /// 两端都不加前缀，即两端都包含
        /// </summary>
        None = 0,
        /// <summary>
        /// 仅右端点加前缀，即含左不含右
        /// </summary>
        IncludeLeft = 1,
        /// <summary>
        /// 仅左端点加前缀，即含右不含左
        /// </summary>
        InCludeRight = 2,
        /// <summary>
        /// 两端都加前缀，即两端都不包含
        /// </summary>
        Both = 3
    }
}
