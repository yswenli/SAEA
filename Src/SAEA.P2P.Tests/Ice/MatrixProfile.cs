namespace SAEA.P2P.Tests.Ice
{
    /// <summary>
    /// 参与连通性判定的 NAT 行为类型
    /// </summary>
    public enum MatrixProfile
    {
        /// <summary>
        /// 完全锥形：任何外部端点都可向已建立的映射发入向包
        /// </summary>
        FullCone,

        /// <summary>
        /// 地址受限：只接受已通信过的地址的入向包
        /// </summary>
        Restricted,

        /// <summary>
        /// 端口受限：只接受已通信过的地址与端口的入向包
        /// </summary>
        PortRestricted,

        /// <summary>
        /// 对称型：每个目标端点单独分配映射，外部端口互不相同
        /// </summary>
        Symmetric
    }
}
