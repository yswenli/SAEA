namespace SAEA.Http.Base
{
    /// <summary>
    /// 报头分段写出目标：报头字符串与报头字节两条输出都按同一份分段描述逐段写出，
    /// 由实现各自决定是累积字符还是编码进目标缓冲。
    /// </summary>
    internal interface IHttpHeaderChunkSink
    {
        /// <summary>
        /// 写出一段文本，不追加换行
        /// </summary>
        /// <param name="value">文本段，允许为 null（按空段处理）</param>
        void Text(string value);

        /// <summary>
        /// 写出一段文本并追加一个换行
        /// </summary>
        /// <param name="value">文本段，允许为 null（此时只写换行）</param>
        void Line(string value);

        /// <summary>
        /// 只写一个换行
        /// </summary>
        void Break();
    }
}