namespace SAEA.Http.Model
{
    /// <summary>
    /// 可跨请求复用的 HTTP 上下文标记接口。实现该接口表示同一条连接上的后续请求会复用同一个实例，
    /// 复用前框架调用 <see cref="ResetForNextRequest"/> 把上一次请求的状态清干净。
    /// <para>
    /// 未实现该接口的 <see cref="IHttpContext"/> 仍按请求创建并在请求结束后释放，行为不变。
    /// 复用只在单条连接内串行发生（HTTP 管道同一连接同时只处理一条消息）。
    /// </para>
    /// </summary>
    public interface IReusableHttpContext : IHttpContext
    {
        /// <summary>
        /// 复位上下文，使同一个实例可以处理本连接的下一条请求；实现里必须把上一次请求留下的状态
        /// 还原成新建实例的初始值，否则会发生跨请求串数据。
        /// </summary>
        void ResetForNextRequest();
    }
}